"""Optional browser integration checks. Install Playwright and Chromium first."""
from playwright.sync_api import sync_playwright, expect

import os
URL=os.environ.get('GAME_TEST_URL','http://localhost:8501')
with sync_playwright() as p:
    browser=p.chromium.launch()
    context=browser.new_context(viewport={'width':1440,'height':1150})
    page=context.new_page(); errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto(URL)
    frame=page.frame_locator('iframe[title="app.snakes_ladders"]')
    expect(frame.locator('[data-mode="local"]')).to_be_visible(timeout=30000)
    frame.locator('[data-mode="local"]').click()
    frame.locator('[data-count="4"]').click()
    frame.locator('#start').click()
    expect(frame.locator('.player-card')).to_have_count(4,timeout=15000)
    expect(frame.locator('#dice-0')).to_be_enabled(timeout=10000)
    assert frame.locator('.token').count()==4
    page.screenshot(path='/tmp/clubhouse-four-players.png',full_page=True)
    frame.locator('#dice-0').click()
    expect(frame.locator('#dice-1')).to_be_enabled(timeout=15000)
    assert frame.locator('#position-0').inner_text()!='At the start'
    frame.locator('#dice-1').click()
    expect(frame.locator('#dice-2')).to_be_enabled(timeout=15000)
    frame.locator('#exit').click()
    expect(frame.locator('[data-mode="computer"]')).to_be_visible(timeout=10000)
    frame.locator('[data-mode="computer"]').click()
    frame.locator('[data-count="4"]').click()
    frame.locator('#start').click()
    expect(frame.locator('#dice-0')).to_be_enabled(timeout=10000)
    frame.locator('#dice-0').click()
    expect(frame.locator('#dice-0')).to_be_enabled(timeout=30000)
    for i in (1,2,3):
        assert frame.locator(f'#position-{i}').inner_text()!='At the start', f'Computer {i} did not move'
    frame.locator('#exit').click()
    expect(frame.locator('[data-mode="friends"]')).to_be_visible(timeout=10000)
    frame.locator('[data-mode="friends"]').click()
    frame.locator('#name').fill('Alice')
    frame.locator('#start').click()
    expect(frame.locator('.room-code')).to_be_visible(timeout=10000)
    code=frame.locator('.room-code').inner_text()
    guest_context=browser.new_context(viewport={'width':390,'height':844},is_mobile=True)
    guest=guest_context.new_page();guest.on('pageerror',lambda error:errors.append(str(error)))
    guest.goto(URL)
    gf=guest.frame_locator('iframe[title="app.snakes_ladders"]')
    expect(gf.locator('[data-mode="friends"]')).to_be_visible(timeout=30000)
    guest.screenshot(path='/tmp/clubhouse-mobile-home.png',full_page=True)
    gf.locator('[data-mode="friends"]').click()
    gf.locator('[data-tab="join"]').click()
    gf.locator('#name').fill('Bob')
    gf.locator('#room-input').fill(code)
    gf.locator('#start').click()
    expect(gf.locator('.room-code')).to_have_text(code,timeout=10000)
    expect(frame.locator('#begin')).to_be_enabled(timeout=10000)
    frame.locator('#begin').click()
    expect(frame.locator('#dice-0')).to_be_enabled(timeout=10000)
    expect(gf.locator('#dice-0')).to_be_disabled(timeout=10000)
    frame.locator('#dice-0').click()
    expect(gf.locator('#dice-1')).to_be_enabled(timeout=15000)
    assert gf.locator('#position-0').inner_text()==frame.locator('#position-0').inner_text()
    gf.locator('#dice-1').click()
    expect(frame.locator('#dice-0')).to_be_enabled(timeout=15000)
    assert gf.locator('#position-1').inner_text()==frame.locator('#position-1').inner_text()
    guest.screenshot(path='/tmp/clubhouse-mobile-game.png',full_page=True)
    assert not errors,errors
    print('PASS: four players, movement, rotating dice, three automatic CPUs, friend room sync and turn permissions, mobile home/game, no JS errors.')
    browser.close()
